CREATE TABLE EMPLOYEE_SKILL_PROGRESS (
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    SKILL_NAME NVARCHAR(255) NOT NULL,
    INFERRED_PROFICIENCY NVARCHAR(30) NOT NULL DEFAULT 'Intermediate',
    EVIDENCE_CONFIDENCE DECIMAL(5,2) NOT NULL DEFAULT 0.50,
    LAST_EVIDENCE_AT DATE NULL,
    PROJECT_EVIDENCE_COUNT INTEGER NOT NULL DEFAULT 0,
    LEARNING_PROGRESS_SCORE DECIMAL(5,2) NOT NULL DEFAULT 0,
    EMPLOYEE_CONFIRMED INTEGER NOT NULL DEFAULT 1,
    MANAGER_VALIDATED INTEGER NOT NULL DEFAULT 0,
    MANAGER_NOTE NVARCHAR(1000),
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, SKILL_NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE EMPLOYEE_CAREER_GOALS (
    EMPLOYEE_ID NVARCHAR(50) PRIMARY KEY,
    TARGET_ROLE NVARCHAR(255),
    PREFERRED_DEPARTMENT NVARCHAR(255),
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE EMPLOYEE_PROJECTS (
    PROJECT_ID NVARCHAR(80) PRIMARY KEY,
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    PROJECT_NAME NVARCHAR(255) NOT NULL,
    DESCRIPTION NVARCHAR(2000) NOT NULL,
    SKILLS_USED NVARCHAR(2000),
    OUTCOME NVARCHAR(1000),
    STARTED_AT DATE,
    COMPLETED_AT DATE,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);
