-- Run this file first, then run skill_taxonomy_seed.sql.

CREATE TABLE IF NOT EXISTS EMPLOYEES (
    EMPLOYEE_ID VARCHAR(50) PRIMARY KEY,
    FULL_NAME VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(320),
    PASSWORD_HASH VARCHAR(255),
    MUST_CHANGE_PASSWORD TINYINT NOT NULL DEFAULT 1,
    PROFILE_TEXT LONGTEXT,
    CURRENT_ROLE VARCHAR(255),
    GRADE VARCHAR(50),
    YEARS_EXPERIENCE DECIMAL(5,2),
    HAS_CAREER_BREAK TINYINT NOT NULL DEFAULT 0,
    IS_CONFIRMED TINYINT NOT NULL DEFAULT 0,
    READY_FOR_MATCHING TINYINT NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS HR_USERS (
    HR_ID VARCHAR(50) PRIMARY KEY,
    FULL_NAME VARCHAR(255) NOT NULL,
    EMAIL VARCHAR(320) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    DEPARTMENT VARCHAR(100),
    IS_ACTIVE TINYINT NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS EMPLOYEE_DOCUMENTS (
    DOCUMENT_ID VARCHAR(100) PRIMARY KEY,
    EMPLOYEE_ID VARCHAR(50) NOT NULL,
    FILE_NAME VARCHAR(500) NOT NULL,
    DOCUMENT_TYPE VARCHAR(100),
    MIME_TYPE VARCHAR(255),
    FILE_CONTENT LONGBLOB NOT NULL,
    EXTRACTED_TEXT LONGTEXT,
    PROCESSING_STATUS VARCHAR(40) NOT NULL DEFAULT 'PENDING',
    FILE_HASH CHAR(64),
    UPLOADED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID),
    INDEX IDX_DOCUMENT_EMPLOYEE (EMPLOYEE_ID),
    INDEX IDX_DOCUMENT_HASH (EMPLOYEE_ID, FILE_HASH)
);

CREATE TABLE IF NOT EXISTS EXTRACTED_SKILLS_DRAFT (
    EMPLOYEE_ID VARCHAR(50) NOT NULL,
    SKILL_ID VARCHAR(100) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    TAXONOMY_CATEGORY VARCHAR(255),
    EVIDENCE_SNIPPET TEXT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, SKILL_ID, NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS CONFIRMED_SKILLS_FINAL (
    EMPLOYEE_ID VARCHAR(50) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    TAXONOMY_CATEGORY VARCHAR(255),
    EVIDENCE_SNIPPET TEXT,
    CONFIRMED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS SKILL_TAXONOMY (
    SKILL_ID VARCHAR(80) PRIMARY KEY,
    CANONICAL_NAME VARCHAR(255) NOT NULL,
    CATEGORY VARCHAR(255) NOT NULL,
    IS_ACTIVE TINYINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS SKILL_TAXONOMY_ALIASES (
    SKILL_ID VARCHAR(80) NOT NULL,
    ALIAS VARCHAR(255) NOT NULL,
    PRIMARY KEY (SKILL_ID, ALIAS),
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

CREATE TABLE IF NOT EXISTS EMPLOYEE_SKILL_PROGRESS (
    EMPLOYEE_ID VARCHAR(50) NOT NULL,
    SKILL_NAME VARCHAR(255) NOT NULL,
    INFERRED_PROFICIENCY VARCHAR(30) NOT NULL DEFAULT 'Intermediate',
    EVIDENCE_CONFIDENCE DECIMAL(5,2) NOT NULL DEFAULT 0.50,
    LAST_EVIDENCE_AT DATE,
    PROJECT_EVIDENCE_COUNT INT NOT NULL DEFAULT 0,
    EMPLOYEE_CONFIRMED TINYINT NOT NULL DEFAULT 1,
    MANAGER_VALIDATED TINYINT NOT NULL DEFAULT 0,
    MANAGER_NOTE VARCHAR(1000),
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, SKILL_NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS JOB_ROLES (
    JOB_ROLE_ID VARCHAR(100) PRIMARY KEY,
    TITLE VARCHAR(150) NOT NULL,
    DEPARTMENT VARCHAR(100),
    DESCRIPTION TEXT,
    EXPERIENCE_MIN DECIMAL(5,2),
    EXPERIENCE_MAX DECIMAL(5,2),
    ROLE_SOURCE VARCHAR(40) NOT NULL DEFAULT 'predefined',
    CREATED_BY_HR VARCHAR(50),
    STATUS VARCHAR(20) NOT NULL DEFAULT 'active',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (CREATED_BY_HR) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE IF NOT EXISTS JOB_REQUIRED_SKILLS (
    REQUIREMENT_ID VARCHAR(100) PRIMARY KEY,
    JOB_ROLE_ID VARCHAR(100) NOT NULL,
    SKILL_NAME VARCHAR(255) NOT NULL,
    TAXONOMY_CATEGORY VARCHAR(255),
    REQUIRED_PROFICIENCY VARCHAR(30),
    IS_MANDATORY TINYINT NOT NULL DEFAULT 1,
    WEIGHT DECIMAL(6,2) NOT NULL DEFAULT 1.00,
    FOREIGN KEY (JOB_ROLE_ID) REFERENCES JOB_ROLES(JOB_ROLE_ID)
);

CREATE TABLE IF NOT EXISTS MATCHING_RESULTS (
    MATCH_ID VARCHAR(100) PRIMARY KEY,
    EMPLOYEE_ID VARCHAR(50) NOT NULL,
    JOB_ROLE_ID VARCHAR(100) NOT NULL,
    MATCH_SCORE DECIMAL(7,4),
    MATCH_STATUS VARCHAR(40) NOT NULL DEFAULT 'completed',
    MATCH_EXPLANATION JSON,
    MATCHED_SKILLS JSON,
    MISSING_SKILLS JSON,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_MATCH_EMPLOYEE_ROLE (EMPLOYEE_ID, JOB_ROLE_ID),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID),
    FOREIGN KEY (JOB_ROLE_ID) REFERENCES JOB_ROLES(JOB_ROLE_ID)
);

CREATE TABLE IF NOT EXISTS BIAS_AUDIT_FLAGS (
    FLAG_ID VARCHAR(100) PRIMARY KEY,
    JOB_ROLE_ID VARCHAR(100) NOT NULL,
    MATCH_ID VARCHAR(100),
    FLAG_TYPE VARCHAR(100) NOT NULL,
    SEVERITY VARCHAR(30) NOT NULL,
    DESCRIPTION TEXT NOT NULL,
    RECOMMENDATION TEXT,
    REVIEW_STATUS VARCHAR(40) NOT NULL DEFAULT 'pending',
    REVIEWED_BY_HR VARCHAR(50),
    REVIEWED_AT TIMESTAMP NULL,
    REVIEW_COMMENTS TEXT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UQ_BIAS_FLAG (JOB_ROLE_ID, MATCH_ID, FLAG_TYPE),
    FOREIGN KEY (JOB_ROLE_ID) REFERENCES JOB_ROLES(JOB_ROLE_ID),
    FOREIGN KEY (MATCH_ID) REFERENCES MATCHING_RESULTS(MATCH_ID),
    FOREIGN KEY (REVIEWED_BY_HR) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE IF NOT EXISTS HR_REVIEW_DECISIONS (
    DECISION_ID VARCHAR(100) PRIMARY KEY,
    MATCH_ID VARCHAR(100) NOT NULL,
    HR_ID VARCHAR(50) NOT NULL,
    DECISION VARCHAR(50) NOT NULL,
    COMMENTS TEXT,
    OVERRIDE_REASON TEXT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (MATCH_ID) REFERENCES MATCHING_RESULTS(MATCH_ID),
    FOREIGN KEY (HR_ID) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE IF NOT EXISTS AUDIT_LOGS (
    LOG_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    EMPLOYEE_ID VARCHAR(50),
    ACTOR VARCHAR(255) NOT NULL,
    ACTION VARCHAR(255) NOT NULL,
    TOOL VARCHAR(255) NOT NULL,
    DETAILS JSON,
    LOG_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE IF NOT EXISTS HR_AUDIT_LOGS (
    LOG_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    HR_ID VARCHAR(50) NOT NULL,
    ACTION VARCHAR(100) NOT NULL,
    ENTITY_TYPE VARCHAR(100) NOT NULL,
    ENTITY_ID VARCHAR(100) NOT NULL,
    DETAILS TEXT,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (HR_ID) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE IF NOT EXISTS MARKET_DEMAND (
    SKILL_ID VARCHAR(80) PRIMARY KEY,
    DEMAND_LEVEL VARCHAR(40) NOT NULL,
    TREND VARCHAR(100) NOT NULL,
    OPEN_INTERNAL_ROLES INT NOT NULL DEFAULT 0,
    MARKET_NOTE VARCHAR(1000) NOT NULL,
    IS_SIMULATED TINYINT NOT NULL DEFAULT 1,
    IS_ACTIVE TINYINT NOT NULL DEFAULT 1,
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

CREATE TABLE IF NOT EXISTS LEARNING_COURSES (
    COURSE_ID VARCHAR(100) PRIMARY KEY,
    TITLE VARCHAR(500) NOT NULL,
    SKILL_ID VARCHAR(80) NOT NULL,
    DURATION_HOURS DECIMAL(6,2) NOT NULL,
    SAP_LEARNING_HUB_URL VARCHAR(1000) NOT NULL,
    IS_ACTIVE TINYINT NOT NULL DEFAULT 1,
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

