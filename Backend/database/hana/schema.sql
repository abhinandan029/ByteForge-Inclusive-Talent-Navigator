CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID NVARCHAR(50) PRIMARY KEY,
    FULL_NAME NVARCHAR(255) NOT NULL,
    EMAIL NVARCHAR(320),
    PASSWORD_HASH NVARCHAR(255),
    MUST_CHANGE_PASSWORD INTEGER NOT NULL DEFAULT 1,
    PROFILE_TEXT NCLOB,
    STATUS NVARCHAR(50) NOT NULL DEFAULT 'draft',
    CURRENT_ROLE NVARCHAR(255),
    GRADE NVARCHAR(50),
    YEARS_EXPERIENCE DECIMAL(5,2),
    HAS_CAREER_BREAK INTEGER NOT NULL DEFAULT 0,
    IS_CONFIRMED INTEGER NOT NULL DEFAULT 0,
    READY_FOR_MATCHING INTEGER NOT NULL DEFAULT 0,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE HR_USERS (
    HR_ID NVARCHAR(50) PRIMARY KEY,
    FULL_NAME NVARCHAR(255) NOT NULL,
    EMAIL NVARCHAR(320) NOT NULL,
    PASSWORD_HASH NVARCHAR(255) NOT NULL,
    DEPARTMENT NVARCHAR(100),
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE EMPLOYEE_DOCUMENTS (
    DOCUMENT_ID NVARCHAR(100) PRIMARY KEY,
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    FILE_NAME NVARCHAR(500) NOT NULL,
    DOCUMENT_TYPE NVARCHAR(100),
    MIME_TYPE NVARCHAR(255),
    FILE_CONTENT BLOB NOT NULL,
    EXTRACTED_TEXT NCLOB,
    PROCESSING_STATUS NVARCHAR(40) NOT NULL DEFAULT 'PENDING',
    FILE_HASH CHAR(64),
    UPLOADED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE EXTRACTED_SKILLS_DRAFT (
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    SKILL_ID NVARCHAR(100) NOT NULL,
    NAME NVARCHAR(255) NOT NULL,
    TAXONOMY_CATEGORY NVARCHAR(255),
    EVIDENCE_SNIPPET NCLOB,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, SKILL_ID, NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE CONFIRMED_SKILLS_FINAL (
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    NAME NVARCHAR(255) NOT NULL,
    TAXONOMY_CATEGORY NVARCHAR(255),
    EVIDENCE_SNIPPET NCLOB,
    CONFIRMED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE SKILL_TAXONOMY (
    SKILL_ID NVARCHAR(80) PRIMARY KEY,
    CANONICAL_NAME NVARCHAR(255) NOT NULL,
    CATEGORY NVARCHAR(255) NOT NULL,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE SKILL_TAXONOMY_ALIASES (
    SKILL_ID NVARCHAR(80) NOT NULL,
    ALIAS NVARCHAR(255) NOT NULL,
    PRIMARY KEY (SKILL_ID, ALIAS),
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

CREATE TABLE EMPLOYEE_SKILL_PROGRESS (
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    SKILL_NAME NVARCHAR(255) NOT NULL,
    INFERRED_PROFICIENCY NVARCHAR(30) NOT NULL DEFAULT 'Intermediate',
    EVIDENCE_CONFIDENCE DECIMAL(5,2) NOT NULL DEFAULT 0.50,
    LAST_EVIDENCE_AT DATE,
    PROJECT_EVIDENCE_COUNT INT NOT NULL DEFAULT 0,
    EMPLOYEE_CONFIRMED INTEGER NOT NULL DEFAULT 1,
    MANAGER_VALIDATED INTEGER NOT NULL DEFAULT 0,
    MANAGER_NOTE NVARCHAR(1000),
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (EMPLOYEE_ID, SKILL_NAME),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE JOB_ROLES (
    JOB_ROLE_ID NVARCHAR(100) PRIMARY KEY,
    TITLE NVARCHAR(150) NOT NULL,
    DEPARTMENT NVARCHAR(100),
    DESCRIPTION NCLOB,
    EXPERIENCE_MIN DECIMAL(5,2),
    EXPERIENCE_MAX DECIMAL(5,2),
    ROLE_SOURCE NVARCHAR(40) NOT NULL DEFAULT 'predefined',
    CREATED_BY_HR NVARCHAR(50),
    STATUS NVARCHAR(20) NOT NULL DEFAULT 'active',
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CREATED_BY_HR) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE JOB_REQUIRED_SKILLS (
    REQUIREMENT_ID NVARCHAR(100) PRIMARY KEY,
    JOB_ROLE_ID NVARCHAR(100) NOT NULL,
    SKILL_NAME NVARCHAR(255) NOT NULL,
    TAXONOMY_CATEGORY NVARCHAR(255),
    REQUIRED_PROFICIENCY NVARCHAR(30),
    IS_MANDATORY INTEGER NOT NULL DEFAULT 1,
    WEIGHT DECIMAL(6,2) NOT NULL DEFAULT 1.00,
    FOREIGN KEY (JOB_ROLE_ID) REFERENCES JOB_ROLES(JOB_ROLE_ID)
);

CREATE TABLE MATCHING_RESULTS (
    MATCH_ID NVARCHAR(100) PRIMARY KEY,
    EMPLOYEE_ID NVARCHAR(50) NOT NULL,
    JOB_ROLE_ID NVARCHAR(100) NOT NULL,
    MATCH_SCORE DECIMAL(7,4),
    MATCH_STATUS NVARCHAR(40) NOT NULL DEFAULT 'completed',
    MATCH_EXPLANATION NCLOB,
    MATCHED_SKILLS NCLOB,
    MISSING_SKILLS NCLOB,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_MATCH_EMPLOYEE_ROLE UNIQUE (EMPLOYEE_ID, JOB_ROLE_ID),
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID),
    FOREIGN KEY (JOB_ROLE_ID) REFERENCES JOB_ROLES(JOB_ROLE_ID)
);

CREATE TABLE BIAS_AUDIT_FLAGS (
    FLAG_ID NVARCHAR(100) PRIMARY KEY,
    JOB_ROLE_ID NVARCHAR(100) NOT NULL,
    MATCH_ID NVARCHAR(100),
    FLAG_TYPE NVARCHAR(100) NOT NULL,
    SEVERITY NVARCHAR(30) NOT NULL,
    DESCRIPTION NCLOB NOT NULL,
    RECOMMENDATION NCLOB,
    REVIEW_STATUS NVARCHAR(40) NOT NULL DEFAULT 'pending',
    REVIEWED_BY_HR NVARCHAR(50),
    REVIEWED_AT TIMESTAMP NULL,
    REVIEW_COMMENTS NCLOB,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_BIAS_FLAG UNIQUE (JOB_ROLE_ID, MATCH_ID, FLAG_TYPE),
    FOREIGN KEY (JOB_ROLE_ID) REFERENCES JOB_ROLES(JOB_ROLE_ID),
    FOREIGN KEY (MATCH_ID) REFERENCES MATCHING_RESULTS(MATCH_ID),
    FOREIGN KEY (REVIEWED_BY_HR) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE HR_REVIEW_DECISIONS (
    DECISION_ID NVARCHAR(100) PRIMARY KEY,
    MATCH_ID NVARCHAR(100) NOT NULL,
    HR_ID NVARCHAR(50) NOT NULL,
    DECISION NVARCHAR(50) NOT NULL,
    COMMENTS NCLOB,
    OVERRIDE_REASON NCLOB,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (MATCH_ID) REFERENCES MATCHING_RESULTS(MATCH_ID),
    FOREIGN KEY (HR_ID) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE AUDIT_LOGS (
    LOG_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID NVARCHAR(50),
    ACTOR NVARCHAR(255) NOT NULL,
    ACTION NVARCHAR(255) NOT NULL,
    TOOL NVARCHAR(255) NOT NULL,
    DETAILS NCLOB,
    LOG_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (EMPLOYEE_ID) REFERENCES EMPLOYEES(EMPLOYEE_ID)
);

CREATE TABLE HR_AUDIT_LOGS (
    LOG_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    HR_ID NVARCHAR(50) NOT NULL,
    ACTION NVARCHAR(100) NOT NULL,
    ENTITY_TYPE NVARCHAR(100) NOT NULL,
    ENTITY_ID NVARCHAR(100) NOT NULL,
    DETAILS NCLOB,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (HR_ID) REFERENCES HR_USERS(HR_ID)
);

CREATE TABLE INTERNAL_ROLES (
    ROLE_ID NVARCHAR(80) PRIMARY KEY,
    TITLE NVARCHAR(255) NOT NULL,
    DEPARTMENT NVARCHAR(255) NOT NULL,
    GRADE_LEVEL NVARCHAR(20) NOT NULL,
    DESCRIPTION NCLOB NOT NULL,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE ROLE_CRITERIA (
    CRITERION_ID NVARCHAR(80) PRIMARY KEY,
    ROLE_ID NVARCHAR(80) NOT NULL,
    DESCRIPTION NCLOB NOT NULL,
    BUSINESS_REASON NCLOB,
    FOREIGN KEY (ROLE_ID) REFERENCES INTERNAL_ROLES(ROLE_ID)
);

CREATE TABLE ROLE_REQUIRED_SKILLS (
    ROLE_ID NVARCHAR(80) NOT NULL,
    SKILL_ID NVARCHAR(80) NOT NULL,
    IMPORTANCE NVARCHAR(20) NOT NULL DEFAULT 'MANDATORY',
    WEIGHT DECIMAL(3,2) NOT NULL DEFAULT 1.00,
    PRIMARY KEY (ROLE_ID, SKILL_ID),
    FOREIGN KEY (ROLE_ID) REFERENCES INTERNAL_ROLES(ROLE_ID),
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

CREATE TABLE FEW_SHOT_EXTRACTIONS (
    EXAMPLE_ID NVARCHAR(50) PRIMARY KEY,
    INPUT_TEXT NCLOB NOT NULL,
    EXPECTED_EXTRACTION_JSON NCLOB NOT NULL
);

CREATE TABLE FAIRNESS_BIAS_RULES (
    RULE_ID NVARCHAR(50) PRIMARY KEY,
    RULE_CATEGORY NVARCHAR(100) NOT NULL,
    REGEX_PATTERN NVARCHAR(500) NOT NULL,
    SEVERITY NVARCHAR(20) NOT NULL,
    EXPLANATION_TEMPLATE NVARCHAR(1000) NOT NULL
);

CREATE TABLE MARKET_DEMAND (
    SKILL_ID NVARCHAR(80) PRIMARY KEY,
    DEMAND_LEVEL NVARCHAR(40) NOT NULL,
    TREND NVARCHAR(100) NOT NULL,
    DEMAND_GROWTH_PCT DECIMAL(6,2) NOT NULL DEFAULT 0,
    OPEN_INTERNAL_ROLES INT NOT NULL DEFAULT 0,
    MARKET_NOTE NVARCHAR(1000) NOT NULL,
    IS_SIMULATED INTEGER NOT NULL DEFAULT 1,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1,
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

CREATE TABLE LEARNING_COURSES (
    COURSE_ID NVARCHAR(100) PRIMARY KEY,
    TITLE NVARCHAR(500) NOT NULL,
    SKILL_ID NVARCHAR(80) NOT NULL,
    DURATION_HOURS DECIMAL(6,2) NOT NULL,
    SAP_LEARNING_HUB_URL NVARCHAR(1000) NOT NULL,
    IS_ACTIVE INTEGER NOT NULL DEFAULT 1,
    FOREIGN KEY (SKILL_ID) REFERENCES SKILL_TAXONOMY(SKILL_ID)
);

